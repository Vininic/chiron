import {expect,it} from 'vitest';
import fs from 'node:fs';
import crypto from 'node:crypto';
import {OLYMPUS_CONTENT} from './olympus';
import {proseWordCount} from '@/lib/content/blocks';
import {checkChapter,checkSource} from '@/lib/content/contract';
import {editorialMetrics,checkEditorialSource} from '@/lib/content/editorial';
import {applyContentSource} from './materialize';
import {freshIndex} from '@/lib/study/migrate';
const read=(p:string)=>JSON.parse(fs.readFileSync(p,'utf8'));
const hash=(s:string|Buffer)=>crypto.createHash('sha256').update(s).digest('hex');
it('Olympus: fonte guarda-chuva inteira, contratos e piso sem redução',()=>{
 const {index,lib}=applyContentSource(freshIndex(),OLYMPUS_CONTENT);
 expect([lib.chapters.length,lib.sections.length,lib.exercises.length,index.cards.length]).toEqual([12,48,36,48]);
 expect(lib.sections.flatMap(s=>s.blocks).filter(b=>b.kind==='code')).toHaveLength(96);
 expect(new Set(lib.sections.map(s=>s.title)).size).toBe(48);
 expect(lib.sections.filter(s=>proseWordCount(s.blocks)<600)).toEqual([]);
 for(const chapter of lib.chapters)expect(checkChapter(chapter,lib,index),chapter.title).toEqual([]);
 expect(checkSource(index.sources[0],lib,index)).toEqual([]);
 const coverage=read('scripts/olympus-coverage-evidence.json');
 expect(coverage.approved).toBe(true);
 expect(coverage.planningDocuments).toHaveLength(13);
 expect(read('scripts/olympus-example-evidence.json').executions).toHaveLength(96);
 for(const [file,digest] of Object.entries(read('scripts/olympus-example-evidence.json').harnessDigests))expect(hash(fs.readFileSync(file)),file).toBe(digest);
 expect(coverage.uncoveredPlanningDocuments).toEqual([]);
 expect(lib.sections.flatMap(s=>s.blocks).filter(b=>b.kind==='diagram')).toHaveLength(21);
 for(const [file,digest] of Object.entries(coverage.referencedSourceDigests))expect(hash(fs.readFileSync(file)),file).toBe(digest);
});
it('Olympus: autoria, avaliações e escopo dos exemplos auditados',()=>{
 const metrics=editorialMetrics(OLYMPUS_CONTENT);
 expect(metrics.maximumSectionSimilarity).toBeLessThan(.42);
 expect(metrics.maximumCardSimilarity).toBeLessThan(.78);
 expect(metrics.detailedExerciseRatio).toBeGreaterThanOrEqual(.65);
 expect(metrics.duplicatedCodeBlocks).toBe(0);
 expect(OLYMPUS_CONTENT.editorial).toMatchObject({proseReviewed:true,assessmentsReviewed:true,examplesVerified:true});
 expect(checkEditorialSource(OLYMPUS_CONTENT)).toEqual([]);
 const sections=OLYMPUS_CONTENT.chapters.flatMap(c=>c.sections).map(s=>({title:s.title,words:proseWordCount(s.blocks)}));
 fs.writeFileSync('scripts/olympus-editorial-evidence.json',JSON.stringify({generatedAt:new Date().toISOString(),metrics,sections,totalWords:sections.reduce((n,s)=>n+s.words,0),minimumWords:Math.min(...sections.map(s=>s.words)),editorialViolations:checkEditorialSource(OLYMPUS_CONTENT)},null,2)+'\n');
},30000);
const examples=read('scripts/olympus-native-examples.json');
const evidence=read('scripts/olympus-example-evidence.json');
it.each(examples)('Olympus: integridade da execução nativa $title caso $case',(example:any)=>{
 const result=evidence.executions.find((e:any)=>e.title===example.title&&e.case===example.case);
 expect(result.status).toBe('passed');
 expect(hash(example.code)).toBe(result.codeDigest);
 expect(result.actual).toEqual(example.expected);
 const published=OLYMPUS_CONTENT.chapters.flatMap(c=>c.sections).find(s=>s.title===example.title)!.blocks.filter(b=>b.kind==='code')[example.case-1];
 expect(published.kind==='code'&&published.code).toBe(example.code);
 for(const source of result.sources)expect(hash(fs.readFileSync(source.file)),source.file).toBe(source.digest);
});
