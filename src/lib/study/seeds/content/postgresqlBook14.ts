const RESERVAR = [
  "CREATE FUNCTION reservar(p_chave uuid, p_sku text, p_qtd int) RETURNS bigint",
  "LANGUAGE plpgsql AS $$",
  "DECLARE",
  "  v_reserva bigint;",
  "  v_produto bigint;",
  "  v_preco   bigint;",
  "BEGIN",
  "  SELECT id INTO v_reserva FROM reserva WHERE chave_idempotencia = p_chave;",
  "  IF FOUND THEN",
  "    RETURN v_reserva;                       -- repetição: a mesma reserva, sem novo débito",
  "  END IF;",
  "",
  "  UPDATE produto SET estoque = estoque - p_qtd",
  "  WHERE sku = p_sku AND estoque >= p_qtd",
  "  RETURNING id, preco_centavos INTO v_produto, v_preco;",
  "  IF NOT FOUND THEN",
  "    RAISE EXCEPTION 'sem estoque de % para % unidade(s)', p_sku, p_qtd USING ERRCODE = 'AG001';",
  "  END IF;",
  "",
  "  INSERT INTO reserva (chave_idempotencia, produto_id, quantidade, preco_unitario_centavos)",
  "  VALUES (p_chave, v_produto, p_qtd, v_preco)   -- o preço é congelado aqui",
  "  RETURNING id INTO v_reserva;",
  "  RETURN v_reserva;",
  "END $$;",
  "",
];

